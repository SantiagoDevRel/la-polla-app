// Local PostgreSQL only. Creates and removes ONLY its uniquely named synthetic
// fixtures through the safe upsert. Never reads/writes users or predictions.
// Apply migration 093 locally, then: node scripts/test-result-concurrency.mjs
import {execFileSync, spawn} from 'node:child_process';
import assert from 'node:assert/strict';
const container='supabase_db_la-polla';
const prefix=`Codex Result QA ${Date.now()}`;
const args=['exec',container,'psql','-U','postgres','-d','postgres','-v','ON_ERROR_STOP=1','-Atc'];
const query=sql=>execFileSync('docker',[...args,sql],{encoding:'utf8',windowsHide:true}).trim();
const upsert=(key)=>`public.upsert_match_safe('${key}','premier_2025',1,'final','${prefix} home','${prefix} away',NULL,NULL,'2026-09-09T18:00:00Z',NULL,NULL,NULL,'scheduled',NULL,NULL,NULL)`;
async function heldTransaction(label,sql,competing){
 const app=`codex_results_${label}_${Date.now()}`;
 const child=spawn('docker',[...args,`SET application_name='${app}'; BEGIN; ${sql}; SELECT pg_sleep(3); COMMIT;`],{windowsHide:true,stdio:['ignore','pipe','pipe']});
 let errors='';child.stderr.on('data',d=>errors+=d);child.stdout.resume();
 const done=new Promise((resolve,reject)=>{child.on('error',reject);child.on('close',code=>code===0?resolve():reject(new Error(errors)));});
 let holding=false;
 for(let i=0;i<30;i++){
  holding=query(`SELECT count(*) FROM pg_stat_activity WHERE application_name='${app}' AND wait_event='PgSleep'`)==='1';
  if(holding)break;
  await new Promise(r=>setTimeout(r,100));
 }
 assert.ok(holding,'First transaction must still hold its lock when the competitor starts');
 const result=competing();
 await done;
 return result;
}
try {
 await heldTransaction('discovery',`SELECT ${upsert(prefix+':espn')}`,()=>query(`SELECT ${upsert(prefix+':fd')}`));
 assert.equal(query(`SELECT count(*) FROM matches WHERE home_team='${prefix} home' AND away_team='${prefix} away'`),'1','Concurrent providers must share one UUID');
 const id=query(`SELECT id FROM matches WHERE home_team='${prefix} home' AND away_team='${prefix} away'`);
 // A first observation after ET must not turn an arbitrary stored score into 90'.
 query(`SELECT public.update_match_live_espn('${id}',NULL,'live',2,1,120,'STATUS_FINAL_AET')`);
 assert.equal(query(`SELECT regulation_home_score IS NULL AND regulation_away_score IS NULL FROM matches WHERE id='${id}'`),'t');
 const liveResult=await heldTransaction('final',`SELECT public.finalize_verified_match_result('${id}',1,1,'QA regulation',2,1,NULL,NULL,'home')`,
  ()=>query(`SELECT public.update_match_live_espn('${id}',NULL,'finished',8,0,120,'STATUS_FINAL_AET')`));
 assert.equal(liveResult,'f','A late live tick must not overwrite the verified score');
 assert.equal(query(`SELECT home_score||':'||away_score||':'||fulltime_home_score||':'||fulltime_away_score FROM matches WHERE id='${id}'`),'1:1:2:1');
 assert.equal(query(`SELECT public.finalize_match_result('${id}',9,0,'second finalizer')`),'f');
 assert.equal(query(`SELECT public.finalize_verified_match_result('${id}',9,0,'second wrapper',9,0)`),'f');
 assert.equal(query(`SELECT has_function_privilege('authenticated','public.finalize_verified_match_result(uuid,integer,integer,text,integer,integer,integer,integer,text)','EXECUTE')`),'f');
 console.log('PASS: concurrent semantic discovery, live-vs-final race, 90-minute score, atomic extras, immutable finalization and private RPC.');
} finally {
 // These exact names were generated by this process and never belong to user fixtures.
 query(`DELETE FROM matches WHERE home_team='${prefix} home' AND away_team='${prefix} away' AND external_id IN ('${prefix}:espn','${prefix}:fd')`);
}
